#!/usr/bin/env python3
"""Generate the built-in demo voice message as 4-bit IMA-ADPCM.

The eCard demo message ("妈妈给你留言") used to play as silence because the
network stub carries no audio payload. This script renders one short line with
the local macOS `say` voice, converts it to the firmware's 16 kHz mono format,
normalizes the level, and encodes it with exactly the same IMA-ADPCM variant
that `main/ecard_voice.c` decodes. The result is a ~30 KB const array in
`assets/sounds/ecard_demo_voice.c`.

Requirements: macOS with `say` and `afconvert` (both ship with the system).
The clip is a demo placeholder only; real messages come from Xiaozhi TTS.

Usage:
    python3 tools/generate_ecard_demo_voice.py
"""

from __future__ import annotations

import shutil
import struct
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = REPO_ROOT / "assets" / "sounds" / "ecard_demo_voice.c"

VOICE = "Tingting"
TEXT = "远豪，妈妈给你留了一条语音，放学记得早点回家，写完作业再玩哦。"
SAMPLE_RATE = 16000
PEAK_TARGET = 0.62  # -4 dBFS: loud enough on a 1 W speaker, no clipping

STEP_TABLE = (
    7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45,
    50, 55, 60, 66, 73, 80, 88, 97, 107, 118, 130, 143, 157, 173, 190, 209, 230,
    253, 279, 307, 337, 371, 408, 449, 494, 544, 598, 658, 724, 796, 876, 963,
    1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327,
    3660, 4026, 4428, 4871, 5358, 5894, 6484, 7132, 7845, 8630, 9493, 10442, 11487,
    12635, 13899, 15289, 16818, 18500, 20350, 22385, 24623, 27086, 29794, 32767,
)
INDEX_TABLE = (-1, -1, -1, -1, 2, 4, 6, 8, -1, -1, -1, -1, 2, 4, 6, 8)


def render_pcm(target: Path) -> bytes:
    aiff = target.with_suffix(".aiff")
    wav = target.with_suffix(".wav")
    subprocess.run(["say", "-v", VOICE, "-o", str(aiff), TEXT], check=True)
    subprocess.run(
        [
            "afconvert",
            "-f", "WAVE",
            "-d", f"LEI16@{SAMPLE_RATE}",
            "-c", "1",
            str(aiff),
            str(wav),
        ],
        check=True,
    )
    with wave.open(str(wav), "rb") as handle:
        if handle.getnchannels() != 1 or handle.getsampwidth() != 2:
            raise SystemExit("afconvert produced an unexpected format")
        if handle.getframerate() != SAMPLE_RATE:
            raise SystemExit(f"unexpected sample rate: {handle.getframerate()}")
        return handle.readframes(handle.getnframes())


def normalize(pcm: bytes) -> tuple[int, ...]:
    samples = list(struct.unpack("<%dh" % (len(pcm) // 2), pcm))
    peak = max((abs(s) for s in samples), default=0)
    if peak == 0:
        raise SystemExit("rendered audio is silent")
    gain = (PEAK_TARGET * 32767.0) / peak
    scaled = []
    for sample in samples:
        value = int(round(sample * gain))
        scaled.append(max(-32768, min(32767, value)))
    # The decoder starts from silence; prepend a few silent samples so the
    # ADPCM step index has settled before the first spoken syllable.
    return tuple([0] * (SAMPLE_RATE // 100)) + tuple(scaled)


def encode_adpcm(samples: tuple[int, ...]) -> list[int]:
    predicted = 0
    index = 0
    out: list[int] = []
    low = None
    for sample in samples:
        diff = sample - predicted
        nibble = 0
        if diff < 0:
            nibble = 8
            diff = -diff
        step = STEP_TABLE[index]
        delta = step >> 3
        if diff >= step:
            nibble |= 4
            diff -= step
            delta += step
        if diff >= (step >> 1):
            nibble |= 2
            diff -= step >> 1
            delta += step >> 1
        if diff >= (step >> 2):
            nibble |= 1
            delta += step >> 2
        predicted += -delta if nibble & 8 else delta
        predicted = max(-32768, min(32767, predicted))
        index += INDEX_TABLE[nibble]
        index = max(0, min(88, index))

        if low is None:
            low = nibble
        else:
            out.append(low | (nibble << 4))
            low = None
    if low is not None:
        out.append(low)
    return out


def write_c(data: list[int], duration_sec: int) -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "/*",
        " * Generated by tools/generate_ecard_demo_voice.py -- do not edit by hand.",
        f" * Demo message rendered with macOS `say -v {VOICE}`:",
        f' * "{TEXT}"',
        " * Format: 4-bit IMA-ADPCM, 16 kHz mono, decoder state starts at 0/0.",
        " * The clip is a placeholder for the network voice message; replace it",
        " * once Xiaozhi TTS provides real audio.",
        " */",
        '#include "ecard_voice.h"',
        "",
        "const uint8_t ecard_demo_voice_adpcm[] = {",
    ]
    for offset in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02x}" for b in data[offset:offset + 16])
        lines.append(f"    {chunk},")
    lines += [
        "};",
        "",
        f"const size_t ecard_demo_voice_adpcm_len = {len(data)};",
        f"const uint8_t ecard_demo_voice_duration_sec = {duration_sec};",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    for tool in ("say", "afconvert"):
        if shutil.which(tool) is None:
            print(f"ERROR: {tool} not found; this generator needs macOS.", file=sys.stderr)
            return 1

    with tempfile.TemporaryDirectory(prefix="ecard-demo-") as tmp:
        pcm = render_pcm(Path(tmp) / "demo")
    samples = normalize(pcm)
    adpcm = encode_adpcm(samples)
    duration = max(1, round(len(samples) / SAMPLE_RATE))
    write_c(adpcm, duration)
    print(
        f"{OUTPUT.relative_to(REPO_ROOT)}: {len(adpcm)} bytes, "
        f"{len(samples) / SAMPLE_RATE:.2f} s, {duration} s rounded"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
