#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Generate the LVGL 9 Chinese bitmap font for Tianji Liu Yao (天机·六爻).
Generates main/tianji_font_16.c.
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

FONT_PATH = "/System/Library/Fonts/STHeiti Medium.ttc"
FONT_INDEX = 1 # Heiti SC Medium
BPP = 2
SIZE = 16
OUT_PATH = os.path.join(os.path.dirname(__file__), "../main/tianji_font_16.c")

COMMON_SYMBOLS = "，。！？：；、‘’“”（）【】《》…—·￥↑↓○●+-/[]><"
PINYIN_TONES = "āáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜ"

# 64 卦特殊用字确保
HEX_SPECIAL_CHARS = "艮睽夬嗑萃孚贲巽姤蹇乾坤屯蒙需讼师比小畜履泰否同人大有谦豫随蛊临观噬嗑剥复无妄大畜颐大过坎离咸恒遁大壮晋明夷家人损益升困井革鼎震渐归妹丰旅兑涣节中孚小过既济未济"

def get_char_list():
    chars = set()
    # 1. GB2312 level 1 (0xB0..0xD7)
    for hi in range(0xB0, 0xD8):
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes([hi, lo]).decode("gb2312")
                if len(ch) == 1 and 0x4E00 <= ord(ch) <= 0x9FA5:
                    chars.add(ch)
            except UnicodeDecodeError:
                continue

    # 2. Add hex special chars & symbols & pinyin tones
    for ch in HEX_SPECIAL_CHARS:
        chars.add(ch)
    for ch in COMMON_SYMBOLS:
        chars.add(ch)
    for ch in PINYIN_TONES:
        chars.add(ch)

    # 3. Read logic, UI, and net files to ensure every character is included
    for fname in ["../main/tianji_logic.c", "../main/tianji_ui.c", "../main/tianji_net.c"]:
        fpath = os.path.join(os.path.dirname(__file__), fname)
        if os.path.exists(fpath):
            with open(fpath, "r", encoding="utf-8") as f:
                for ch in f.read():
                    if ord(ch) >= 0x80:
                        chars.add(ch)

    sorted_chars = sorted(list(chars), key=ord)
    return sorted_chars

def split_sparse_cmap_chars(chars):
    groups = []
    for ch in chars:
        if not groups or ord(ch) - ord(groups[-1][0]) > 0xFFFF:
            groups.append([])
        groups[-1].append(ch)
    return groups

def pack_bits(vals, bpp):
    out = bytearray()
    acc = nbits = 0
    for v in vals:
        acc = (acc << bpp) | (v & ((1 << bpp) - 1))
        nbits += bpp
        while nbits >= 8:
            nbits -= 8
            out.append((acc >> nbits) & 0xFF)
    if nbits:
        out.append((acc << (8 - nbits)) & 0xFF)
    return bytes(out)

def render_glyph(font, ch, ascent, bpp):
    adv_w = int(round(font.getlength(ch) * 16))
    bbox = font.getbbox(ch)
    if bbox is None:
        return b"", 0, 0, 0, 0, adv_w
    x0, y0, x1, y1 = bbox
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0:
        return b"", 0, 0, 0, 0, adv_w

    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
    shift = 8 - bpp
    vals = [p >> shift for p in img.getdata()]
    return pack_bits(vals, bpp), w, h, x0, ascent - y1, adv_w

def main():
    print(f"Loading font {FONT_PATH} index {FONT_INDEX}...")
    font = ImageFont.truetype(FONT_PATH, SIZE, index=FONT_INDEX)
    ascent, descent = font.getmetrics()

    ascii_chars = [chr(c) for c in range(0x20, 0x7F)] # 95 printable
    cjk_chars = get_char_list()
    all_chars = ascii_chars + cjk_chars
    print(f"Total glyphs to render: ASCII={len(ascii_chars)}, CJK={len(cjk_chars)}")

    bitmap = bytearray()
    dscs = [(0, 0, 0, 0, 0, 0)] # id 0 reserved
    for ch in all_chars:
        bm, bw, bh, ox, oy, aw = render_glyph(font, ch, ascent, BPP)
        dscs.append((len(bitmap), aw, bw, bh, ox, oy))
        bitmap += bm

    cjk_groups = split_sparse_cmap_chars(cjk_chars)
    ascii_gid_start = 1

    L = []
    L.append("// Generated by tools/gen_tianji_font.py; do not edit manually.")
    L.append(f"// Font: STHeiti Medium (Heiti SC) Size:{SIZE}px Bpp:{BPP}bpp")
    L.append(f"// Glyph count: {len(all_chars)} (ASCII 95 + CJK/Symbols {len(cjk_chars)})")
    L.append("// Placed in Flash (.rodata), 0 bytes DRAM overhead.")
    L.append('#include "lvgl.h"')
    L.append("")
    L.append("#if TIANJI_FONT_16_ENABLE || 1")
    L.append("")
    L.append("static const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmap), 16):
        L.append("    " + "".join(f"0x{b:02X}," for b in bitmap[i:i + 16]))
    L.append("};")
    L.append("")
    L.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    for (bi, aw, bw, bh, ox, oy) in dscs:
        L.append(f"    {{.bitmap_index = {bi}, .adv_w = {aw}, .box_w = {bw}, "
                 f".box_h = {bh}, .ofs_x = {ox}, .ofs_y = {oy}}},")
    L.append("};")
    L.append("")
    for group_index, group in enumerate(cjk_groups):
        if len(group) == 1:
            continue
        group_start = ord(group[0])
        offs = [ord(ch) - group_start for ch in group]
        L.append(f"static const uint16_t unicode_list_cjk_{group_index}[] = {{")
        for i in range(0, len(offs), 12):
            L.append("    " + "".join(f"0x{o:04X}, " for o in offs[i:i + 12]).rstrip())
        L.append("};")
        L.append("")
    L.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    L.append("    {")
    L.append(f"        .range_start = 32, .range_length = {len(ascii_chars)}, "
             f".glyph_id_start = {ascii_gid_start},")
    L.append("        .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,")
    L.append("        .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY")
    L.append("    },")
    cjk_gid_start = 1 + len(ascii_chars)
    for group_index, group in enumerate(cjk_groups):
        group_start = ord(group[0])
        group_end = ord(group[-1])
        L.append("    {")
        L.append(f"        .range_start = {group_start}, .range_length = {group_end - group_start + 1}, "
                 f".glyph_id_start = {cjk_gid_start},")
        if len(group) == 1:
            L.append("        .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,")
            L.append("        .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY")
        else:
            L.append(f"        .unicode_list = unicode_list_cjk_{group_index}, .glyph_id_ofs_list = NULL, "
                     f".list_length = {len(group)},")
            L.append("        .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY")
        cjk_gid_start += len(group)
        L.append("    },")
    L.append("};")
    L.append("")
    L.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    L.append("    .glyph_bitmap = glyph_bitmap,")
    L.append("    .glyph_dsc = glyph_dsc,")
    L.append("    .cmaps = cmaps,")
    L.append("    .kern_dsc = NULL,")
    L.append("    .kern_scale = 0,")
    L.append(f"    .cmap_num = {1 + len(cjk_groups)},")
    L.append(f"    .bpp = {BPP},")
    L.append("    .kern_classes = 0,")
    L.append("    .bitmap_format = 0,")
    L.append("};")
    L.append("")
    L.append("const lv_font_t tianji_font_16 = {")
    L.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    L.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    L.append(f"    .line_height = {ascent + descent},")
    L.append(f"    .base_line = {descent},")
    L.append("    .subpx = LV_FONT_SUBPX_NONE,")
    L.append("    .underline_position = -2,")
    L.append("    .underline_thickness = 1,")
    L.append("    .dsc = &font_dsc,")
    L.append("    .fallback = NULL,")
    L.append("    .user_data = NULL,")
    L.append("};")
    L.append("")
    L.append("#endif")
    L.append("")

    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print(f"Generated {OUT_PATH}: size={len(bitmap)/1024:.1f}KB, line_height={ascent+descent}")

if __name__ == "__main__":
    main()
