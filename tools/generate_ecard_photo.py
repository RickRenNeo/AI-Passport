#!/usr/bin/env python3
"""Convert the eCard demo portrait into LVGL 9 RGB565 image descriptors.

Source
    assets/images/ecard_portrait_source.jpg — a synthetic portrait generated
    for this demo. It does not depict a real pupil; replace it with the
    school's authorised photo before production use.

Output
    assets/images/ecard_portrait.c — two const LVGL image descriptors:
    ecard_portrait_home (130 × 184) and ecard_portrait_card (54 × 78).
    The corners are baked to the card surface colour so LVGL does not need a
    clip layer (which costs about 15 KB of the no-PSRAM LVGL pool per draw).

The crop windows are normalised so the face stays centred in both frames.
Run this script after replacing the source image, then rebuild the firmware.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageEnhance, ImageFilter

REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE = REPO_ROOT / "assets" / "images" / "ecard_portrait_source.jpg"
OUTPUT = REPO_ROOT / "assets" / "images" / "ecard_portrait.c"
PREVIEW_DIR = REPO_ROOT / "assets" / "images" / ".ecard_portrait_preview"

# The frame is white; baked corners blend into it without a runtime clip layer.
FRAME_COLOR = (255, 255, 255)

# name, width, height, crop box in fractions (left, top, right, bottom), corner radius
VARIANTS = (
    # 首页照片占 134 × 188 相框的内区；裁到 0.955 高度以裁掉源图右下角水印。
    ("home", 130, 184, (0.050, 0.000, 0.950, 0.955), 12),
    ("card", 54, 78, (0.120, 0.015, 0.880, 0.840), 7),
)


def rgb565_bytes(image: Image.Image) -> bytes:
    """Little-endian RGB565, matching LV_COLOR_FORMAT_RGB565 on ESP32."""
    out = bytearray()
    for r, g, b in image.convert("RGB").getdata():
        value = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        out += bytes((value & 0xFF, value >> 8))
    return bytes(out)


def render_variant(source: Image.Image, width: int, height: int,
                   box: tuple[float, float, float, float],
                   corner_radius: int) -> Image.Image:
    left, top, right, bottom = box
    crop = source.crop(
        (
            round(left * source.width),
            round(top * source.height),
            round(right * source.width),
            round(bottom * source.height),
        )
    )
    crop = crop.resize((width, height), Image.LANCZOS)
    crop = ImageEnhance.Contrast(crop).enhance(1.04)
    crop = ImageEnhance.Color(crop).enhance(1.02)
    crop = crop.filter(ImageFilter.UnsharpMask(radius=0.6, percent=55, threshold=2))

    mask = Image.new("L", (width, height), 0)
    ImageDraw.Draw(mask).rounded_rectangle(
        (0, 0, width - 1, height - 1), radius=corner_radius, fill=255
    )
    framed = Image.new("RGB", (width, height), FRAME_COLOR)
    framed.paste(crop, (0, 0), mask)
    return framed


def emit_array(lines: list[str], name: str, data: bytes) -> None:
    lines.append(f"static const uint8_t {name}_map[] LV_ATTRIBUTE_MEM_ALIGN = {{")
    for start in range(0, len(data), 16):
        chunk = data[start:start + 16]
        lines.append("    " + ", ".join(f"0x{byte:02X}" for byte in chunk) + ",")
    lines.append("};")
    lines.append("")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()

    source = Image.open(args.source)
    PREVIEW_DIR.mkdir(parents=True, exist_ok=True)

    lines = [
        "/* Generated by tools/generate_ecard_photo.py. Do not edit by hand. */",
        '#include "lvgl.h"',
        '#include "ecard_photo.h"',
        "",
    ]

    for name, width, height, box, corner_radius in VARIANTS:
        image = render_variant(source, width, height, box, corner_radius)
        image.save(PREVIEW_DIR / f"ecard_portrait_{name}.png")
        data = rgb565_bytes(image)
        emit_array(lines, f"ecard_portrait_{name}", data)
        lines.extend(
            [
                f"const lv_image_dsc_t ecard_portrait_{name} = {{",
                "    .header.magic = LV_IMAGE_HEADER_MAGIC,",
                "    .header.cf = LV_COLOR_FORMAT_RGB565,",
                f"    .header.w = {width},",
                f"    .header.h = {height},",
                f"    .header.stride = {width * 2},",
                f"    .data_size = sizeof(ecard_portrait_{name}_map),",
                f"    .data = ecard_portrait_{name}_map,",
                "};",
                "",
            ]
        )

    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.output.relative_to(REPO_ROOT)} ({args.output.stat().st_size} bytes)")
    print(f"previews: {PREVIEW_DIR.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
